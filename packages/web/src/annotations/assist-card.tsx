import * as React from "react";
import { createPortal } from "react-dom";
import copy from "copy-to-clipboard";
import { Copy, RotateCw, Sparkles, X } from "lucide-react";
import { failureMessage } from "../api/client";
import { toast } from "../ui/toast";
import { t } from "../i18n";

export type AssistAction = "explain" | "rewrite" | "translate" | "summarize";

const TITLES: Readonly<Record<AssistAction, string>> = { explain: t("AI explanation"), rewrite: t("AI rewrite"), translate: t("AI translation"), summarize: t("AI summary") };

const GAP = 8;
const WIDTH = 460;
/** Roughly the tallest a result gets before it scrolls; the card opens upward when that would not fit below. */
const ROOM_BELOW = 320;

function cardPosition(rect: DOMRect): React.CSSProperties {
  const doc = document.querySelector("main .rp-doc")?.getBoundingClientRect();
  const min = Math.max(doc?.left ?? GAP, GAP);
  const max = Math.max(Math.min(doc?.right ?? innerWidth - GAP, innerWidth - GAP) - WIDTH, min);
  const left = Math.min(Math.max(rect.left + rect.width / 2 - WIDTH / 2, min), max) + scrollX;
  const opensUp = rect.bottom + ROOM_BELOW > innerHeight && rect.top > ROOM_BELOW;
  return opensUp ? { left, top: rect.top + scrollY - GAP, transform: "translateY(-100%)" } : { left, top: rect.bottom + scrollY + GAP };
}

type State = { readonly status: "loading" } | { readonly status: "done"; readonly text: string } | { readonly status: "failed"; readonly message: string };

/** Anchored to the page rather than the window, so it stays beside the words it talks about while scrolling. */
export function AssistCard({ rect, action, load, onClose, actions }: { rect?: DOMRect | null | undefined; action: AssistAction; load: () => Promise<{ text: string }>; onClose: () => void; actions?: (text: string) => React.ReactNode }) {
  const [state, setState] = React.useState<State>({ status: "loading" });
  const [attempt, setAttempt] = React.useState(0);
  const ref = React.useRef<HTMLDivElement>(null);
  const [position] = React.useState(() => cardPosition(rect ?? new DOMRect()));

  React.useEffect(() => {
    let current = true;
    setState({ status: "loading" });
    load()
      .then(({ text }) => { if (current) setState({ status: "done", text }); })
      .catch(error => { if (current) setState({ status: "failed", message: failureMessage(error) }); });
    return () => { current = false; };
    // oxlint-disable-next-line react-hooks/exhaustive-deps -- A card is for one request; only asking again runs it again.
  }, [attempt]);

  React.useEffect(() => {
    // Captured first, so that Escape closes this card and not the discussion panel behind it as well.
    const onKey = (event: KeyboardEvent) => {
      if (event.key !== "Escape") return;
      event.stopPropagation();
      onClose();
    };
    const onPointerDown = (event: MouseEvent) => {
      if (event.target instanceof Node && !ref.current?.contains(event.target)) onClose();
    };
    document.addEventListener("keydown", onKey, true);
    document.addEventListener("mousedown", onPointerDown);
    return () => {
      document.removeEventListener("keydown", onKey, true);
      document.removeEventListener("mousedown", onPointerDown);
    };
  }, [onClose]);

  const done = state.status === "done" ? state : null;
  return createPortal(
    <div ref={ref} className="pd-assist" role="region" aria-label={TITLES[action]} style={position}>
      <header className="pd-assist__head">
        <Sparkles size={15} aria-hidden="true" />
        <strong>{TITLES[action]}</strong>
        <button type="button" className="pd-assist__close" aria-label={t("Close")} onClick={onClose}><X size={15} aria-hidden="true" /></button>
      </header>
      <div className="pd-assist__body" aria-live="polite">
        {state.status === "loading" ? <p className="pd-assist__status">{t("Generating…")}</p> : null}
        {state.status === "failed" ? <p className="pd-assist__status pd-assist__status--failed">{state.message}</p> : null}
        {done ? <p className="pd-assist__text">{done.text}</p> : null}
      </div>
      <footer className="pd-assist__foot">
        <small>{t("Generated by AI. Check it before use.")}</small>
        <span className="pd-assist__actions">
          {state.status !== "loading" ? <button type="button" className="pd-btn" onClick={() => setAttempt(attempt + 1)}><RotateCw size={14} aria-hidden="true" />{t("Regenerate")}</button> : null}
          {done ? <button type="button" className="pd-btn" onClick={() => { copy(done.text); toast(t("Copied")); }}><Copy size={14} aria-hidden="true" />{t("Copy")}</button> : null}
          {done ? actions?.(done.text) : null}
        </span>
      </footer>
    </div>,
    document.body
  );
}
