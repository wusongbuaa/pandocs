import * as React from "react";
import { api } from "../api/client";
import type { PandocsPage } from "../data/pages";
import { RenderedDiff } from "../review/rendered-diff";
import { useReaderContextValue } from "../review/use-reader-context";
import type { ThreadView } from "../types";
import { FormDialog } from "../ui/dialog";
import { TextareaField } from "../ui/form";
import { toast } from "../ui/toast";
import { refreshProposals, setPanelTab } from "./store";
import type { ThreadSuggestion } from "./thread-suggestion";
import { t } from "../i18n";

export default function SuggestionDialog({
  page,
  thread,
  suggestion,
  onClose
}: {
  page: PandocsPage;
  thread: ThreadView;
  suggestion: ThreadSuggestion;
  onClose: () => void;
}) {
  const reader = useReaderContextValue(page);
  const [content, setContent] = React.useState(suggestion.text);
  const [rationale, setRationale] = React.useState(
    t("From the discussion: {0}", thread.comments.at(-1)?.body.slice(0, 60) ?? "")
  );
  const shown = React.useDeferredValue(content);
  const submit = async () => {
    const { baseRevision, firstRef, lastRef } = suggestion;
    await api.send("POST", `documents/${thread.documentId}/proposals`, {
      body: {
        baseRevision,
        rationale,
        threadIds: [thread.id],
        ops: [{ op: "block_replace", ref: firstRef, ...(lastRef === firstRef ? {} : { end: lastRef }), content }]
      }
    });
    toast(t("Suggestion sent. Accepting it resolves this discussion."), "success");
    await refreshProposals();
    setPanelTab("proposals");
    onClose();
  };
  return (
    <FormDialog
      wide
      title={t("Suggestion from the discussion")}
      description={t("Generated by AI. Check it before sending. The page does not change until someone accepts it.")}
      action={t("Send suggestion")}
      disabled={!content.trim() || content === suggestion.source}
      onClose={onClose}
      onSubmit={submit}
    >
      <div className="rp-doc rspress-doc">
        <RenderedDiff before={suggestion.source} after={shown} reader={reader} />
      </div>
      <TextareaField
        label={t("Change to")}
        mono
        rows={Math.min(12, Math.max(3, content.split("\n").length + 1))}
        value={content}
        onChange={event => setContent(event.target.value)}
      />
      <TextareaField
        label={t("Explanation")}
        rows={2}
        value={rationale}
        onChange={event => setRationale(event.target.value)}
      />
    </FormDialog>
  );
}
